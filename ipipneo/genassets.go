//go:build ignore
// +build ignore

// genassets writes assets_gen.go, which embeds the web assets into the
// binary. (go:embed needs Go 1.16; this works with Go 1.10 too.)
//
// Usage: go run genassets.go <static dir> <views dir>
package main

import (
	"bufio"
	"fmt"
	"io/ioutil"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: go run genassets.go <static dir> <views dir>")
	}
	files := map[string]string{}
	add := func(prefix, root string) {
		err := filepath.Walk(root, func(p string, fi os.FileInfo, err error) error {
			if err != nil || fi.IsDir() || strings.HasSuffix(p, ".map") {
				return err
			}
			data, err := ioutil.ReadFile(p)
			if err != nil {
				return err
			}
			rel, _ := filepath.Rel(root, p)
			files[prefix+"/"+filepath.ToSlash(rel)] = string(data)
			return nil
		})
		if err != nil {
			log.Fatal(err)
		}
	}
	add("static", os.Args[1])
	add("views", os.Args[2])

	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)

	f, err := os.Create("assets_gen.go")
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "// Code generated by genassets.go; DO NOT EDIT.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "package main")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "var assets = map[string]string{")
	for _, n := range names {
		fmt.Fprintf(w, "\t%q: %s,\n", n, strconv.Quote(files[n]))
	}
	fmt.Fprintln(w, "}")
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}
